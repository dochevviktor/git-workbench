export function aurSources(
  version: string,
  repository: string,
  appImageSha256: string,
  licenseSha256: string,
) {
  releaseVersion(version);
  releaseRepository(repository);
  for (const hash of [appImageSha256, licenseSha256])
    if (!/^[a-f0-9]{64}$/u.test(hash)) throw new Error('AUR sources require real SHA-256 checksums.');
  const appImage = installerNames(version)[0]!;
  const url = `https://github.com/${repository}`;
  const sources = [
    `${appImage}::${url}/releases/download/v${version}/${appImage}`,
    `LICENSE::https://raw.githubusercontent.com/${repository}/v${version}/LICENSE`,
  ];
  const description = 'A Git desktop client built with Electron (official binary)';
  const pkgbuild = `# Generated by scripts/package-aur.ts from the verified release artifacts.
pkgname=git-workbench-bin
pkgver=${version}
pkgrel=1
pkgdesc='${description}'
arch=('x86_64')
url='${url}'
license=('MIT')
depends=(${depends.map((dependency) => `'${dependency}'`).join(' ')})
optdepends=('git-lfs: Git LFS support' 'openssh: SSH remotes' 'gnupg: GPG commit signing')
provides=("git-workbench=$pkgver")
conflicts=('git-workbench')
options=('!strip' '!debug')
source=('${sources[0]}'
        '${sources[1]}')
noextract=('${appImage}')
sha256sums=('${appImageSha256}'
            '${licenseSha256}')

prepare() {
  chmod +x '${appImage}'
  './${appImage}' --appimage-extract >/dev/null
}

package() {
  install -d "$pkgdir/opt/git-workbench" "$pkgdir/usr/bin"
  cp -a squashfs-root/. "$pkgdir/opt/git-workbench/"
  # Use the bundled Electron directly; AppRun is a portable-image launcher.
  ln -s /opt/git-workbench/git-workbench "$pkgdir/usr/bin/git-workbench"
  install -Dm644 squashfs-root/git-workbench.desktop "$pkgdir/usr/share/applications/git-workbench.desktop"
  sed -i 's|^Exec=.*|Exec=/usr/bin/git-workbench %U|' "$pkgdir/usr/share/applications/git-workbench.desktop"
  install -Dm644 squashfs-root/resources/icon.png "$pkgdir/usr/share/icons/hicolor/512x512/apps/git-workbench.png"
  install -Dm644 LICENSE "$pkgdir/usr/share/licenses/$pkgname/LICENSE"
  # makepkg records root ownership; retain Chromium's sandbox helper permissions.
  chmod 4755 "$pkgdir/opt/git-workbench/chrome-sandbox"
}
`;
  const srcinfo = [
    'pkgbase = git-workbench-bin',
    `\tpkgdesc = ${description}`,
    `\tpkgver = ${version}`,
    '\tpkgrel = 1',
    `\turl = ${url}`,
    '\tarch = x86_64',
    '\tlicense = MIT',
    ...depends.map((dependency) => `\tdepends = ${dependency}`),
    '\toptdepends = git-lfs: Git LFS support',
    '\toptdepends = openssh: SSH remotes',
    '\toptdepends = gnupg: GPG commit signing',
    `\tprovides = git-workbench=${version}`,
    '\tconflicts = git-workbench',
    `\tnoextract = ${appImage}`,
    '\toptions = !strip',
    '\toptions = !debug',
    ...sources.map((source) => `\tsource = ${source}`),
    `\tsha256sums = ${appImageSha256}`,
    `\tsha256sums = ${licenseSha256}`,
    '',
    'pkgname = git-workbench-bin',
    '',
  ].join('\n');
  return { pkgbuild, srcinfo };
}

export async function packageAur(directory: string, version: string, repository: string): Promise<void> {
  const appImage = await digestFile(join(directory, installerNames(version)[0]!));
  const license = await digestFile('LICENSE');
  const { pkgbuild, srcinfo } = aurSources(version, repository, appImage.sha256, license.sha256);
  await mkdir(directory, { recursive: true });
  await writeFile(join(directory, 'PKGBUILD'), pkgbuild);
  await writeFile(join(directory, '.SRCINFO'), srcinfo);
  // GitHub strips leading periods from release asset names. The archive retains .SRCINFO.
  await writeFile(join(directory, 'git-workbench-bin.SRCINFO'), srcinfo);
  const staging = await mkdtemp(join(tmpdir(), 'workbench-aur-'));
  try {
    const root = join(staging, 'git-workbench-bin');
    await mkdir(root);
    for (const file of ['PKGBUILD', '.SRCINFO']) await copyFile(join(directory, file), join(root, file));
    await copyFile('LICENSE', join(root, 'LICENSE'));
    await promisify(execFile)('tar', [
      '-czf',
      resolve(directory, `git-workbench-bin-${version}.tar.gz`),
      '-C',
      staging,
      'git-workbench-bin',
    ]);
  } finally {
    await rm(staging, { recursive: true, force: true });
  }
}

if (import.meta.main) {
  await packageAur(resolve(process.argv[2] ?? 'release'), await readReleaseVersion(), releaseRepository());
  console.info('Generated release/PKGBUILD, .SRCINFO and the AUR source archive.');
}
