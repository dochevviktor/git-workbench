/**
 * Downloads the public Fork screenshots listed in `docs/research/fork-references.json` into a git-ignored
 * folder and writes an index for browsing them. They are design references only: never commit them,
 * bundle them, or copy them into the application.
 *
 * Usage: npm run research:references [-- --force]
 */
import { mkdir, readFile, rename, rm, stat, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { z } from 'zod';

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const manifestPath = join(projectRoot, 'docs/research/fork-references.json');
const maximumBytes = 25 * 1024 * 1024;
const parallelDownloads = 6;

const imageSchema = z.strictObject({
  file: z.string().regex(/^[a-z0-9][a-z0-9.-]*\.(?:png|jpe?g|gif|webp)$/u),
  url: z.url({ protocol: /^https$/u }),
  source: z.url({ protocol: /^https$/u }),
  date: z.iso.date().nullable(),
  platform: z.enum(['windows', 'mac', 'both']),
  version: z.string().min(1).nullable(),
  theme: z.enum(['light', 'dark']),
  topics: z.array(z.string().regex(/^[a-z-]+$/u)).min(1),
  shows: z.string().min(1),
  note: z.string().min(1).nullable(),
});

const manifestSchema = z.strictObject({
  $comment: z.string(),
  accessed: z.iso.date(),
  directory: z.string().regex(/^docs\/research\/[a-z-]+$/u),
  images: z.array(imageSchema).min(1),
});

type ReferenceImage = z.infer<typeof imageSchema>;

interface Collection {
  readonly title: string;
  readonly matches: (image: ReferenceImage) => boolean;
}

const collections: readonly Collection[] = [
  {
    title: 'Fork for Windows issue tracker (user screenshots)',
    matches: (image) => image.source.startsWith('https://github.com/fork-dev/TrackerWin/'),
  },
  {
    title: 'Fork for Mac issue tracker (user screenshots)',
    matches: (image) => image.source.startsWith('https://github.com/fork-dev/Tracker/'),
  },
  { title: 'Official website', matches: (image) => image.source === 'https://fork.dev/' },
  { title: 'Official blog', matches: (image) => image.source.startsWith('https://fork.dev/blog/') },
  { title: 'Other publications', matches: () => true },
];

const platformLabels: Record<ReferenceImage['platform'], string> = {
  windows: 'Windows',
  mac: 'macOS',
  both: 'Mac and Windows',
};

async function exists(path: string): Promise<boolean> {
  try {
    return (await stat(path)).size > 0;
  } catch {
    return false;
  }
}

async function download(image: ReferenceImage, target: string): Promise<void> {
  const response = await fetch(image.url, {
    headers: { accept: 'image/*' },
    redirect: 'follow',
    signal: AbortSignal.timeout(60_000),
  });
  if (!response.ok) throw new Error(`HTTP ${response.status}`);
  const type = response.headers.get('content-type') ?? '';
  if (!type.startsWith('image/')) throw new Error(`expected an image, received ${type || 'no content type'}`);
  const bytes = new Uint8Array(await response.arrayBuffer());
  if (bytes.byteLength === 0 || bytes.byteLength > maximumBytes) {
    throw new Error(`unexpected size of ${bytes.byteLength} bytes`);
  }
  const partial = `${target}.partial`;
  try {
    await writeFile(partial, bytes);
    await rename(partial, target);
  } finally {
    await rm(partial, { force: true });
  }
}

function cell(text: string): string {
  return text.replaceAll('|', '\\|').replaceAll('\n', ' ');
}

function sortNewestFirst(images: readonly ReferenceImage[]): ReferenceImage[] {
  return [...images].sort(
    (left, right) => (right.date ?? '').localeCompare(left.date ?? '') || left.file.localeCompare(right.file),
  );
}

function renderIndex(manifest: z.infer<typeof manifestSchema>): string {
  const lines = [
    '# Fork reference images',
    '',
    `Generated by \`npm run research:references\` from \`docs/research/fork-references.json\` (sources accessed ${manifest.accessed}).`,
    'These are public screenshots kept locally for design comparison. This folder is git-ignored: do not commit',
    'these files or copy them into the application. Record observations and their source URLs in',
    '`docs/research/fork-public-surface.md`; mark anything not visible in an image as inference.',
    '',
    'Dates are publication or issue dates, not necessarily the date of the Fork version shown. Versions are',
    'listed only where the source states them. Annotations and redactions inside user screenshots are the',
    "reporters'. Extract GIF frames with `ffmpeg -i image.gif frames-%03d.png` when an animation matters.",
    '',
    '## By topic',
    '',
  ];
  const topics = [...new Set(manifest.images.flatMap((image) => image.topics))].sort();
  for (const topic of topics) {
    const files = sortNewestFirst(manifest.images.filter((image) => image.topics.includes(topic)));
    lines.push(`- **${topic}**: ${files.map((image) => `[${image.file}](${image.file})`).join(', ')}`);
  }

  const remaining = new Set(manifest.images);
  for (const collection of collections) {
    const images = sortNewestFirst([...remaining].filter(collection.matches));
    if (images.length === 0) continue;
    for (const image of images) remaining.delete(image);
    lines.push(
      '',
      `## ${collection.title}`,
      '',
      '| Image | Date | Platform | Version | Theme | Shows | Source |',
    );
    lines.push('| --- | --- | --- | --- | --- | --- | --- |');
    for (const image of images) {
      const shows = image.note ? `${image.shows} ${image.note}` : image.shows;
      lines.push(
        `| [${image.file}](${image.file}) | ${image.date ?? 'undated'} | ${platformLabels[image.platform]} | ${
          image.version ?? '—'
        } | ${image.theme} | ${cell(shows)} | [source](${image.source}) |`,
      );
    }
  }
  return `${lines.join('\n')}\n`;
}

const manifest = manifestSchema.parse(JSON.parse(await readFile(manifestPath, 'utf8')));
const duplicate = manifest.images.find(
  (image, index) => manifest.images.findIndex((candidate) => candidate.file === image.file) !== index,
);
if (duplicate) throw new Error(`Duplicate reference file name: ${duplicate.file}`);

const force = process.argv.includes('--force');
const directory = join(projectRoot, manifest.directory);
await mkdir(directory, { recursive: true });

const queue = [...manifest.images];
const failures: string[] = [];
let downloaded = 0;
let kept = 0;
await Promise.all(
  Array.from({ length: parallelDownloads }, async () => {
    for (let image = queue.shift(); image; image = queue.shift()) {
      const target = join(directory, image.file);
      if (!force && (await exists(target))) {
        kept += 1;
        continue;
      }
      try {
        await download(image, target);
        downloaded += 1;
      } catch (error) {
        failures.push(
          `${image.file}: ${error instanceof Error ? error.message : String(error)} (${image.url})`,
        );
      }
    }
  }),
);

await writeFile(join(directory, 'INDEX.md'), renderIndex(manifest));
console.log(
  `${manifest.directory}: ${downloaded} downloaded, ${kept} already present, ${failures.length} failed; wrote INDEX.md`,
);
if (failures.length > 0) {
  for (const failure of failures) console.error(`  ${failure}`);
  process.exitCode = 1;
}
